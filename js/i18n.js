let currentLang =
  localStorage.getItem("heriland-lang")
  || "en";

function t(key) {
  return I18N[currentLang]?.[key] || I18N.en[key] || key;
}

function applyLanguage() {

  document.documentElement.lang =
    currentLang;

  document
    .querySelectorAll("[data-i18n]")
    .forEach(el => {
      el.textContent =
        t(el.dataset.i18n);
    });

  document
    .querySelectorAll("[data-i18n-html]")
    .forEach(el => {
      el.innerHTML =
        t(el.dataset.i18nHtml);
    });

  document
    .querySelectorAll("[data-i18n-placeholder]")
    .forEach(el => {
      el.placeholder =
        t(el.dataset.i18nPlaceholder);
    });

  const langBtn =
    document.getElementById("lang-toggle");

if (langBtn) {
  if (currentLang === "en") {
    langBtn.textContent = "简";
  } else if (currentLang === "zh-cn") {
    langBtn.textContent = "繁";
  } else if (currentLang === "zh-tw") {
    langBtn.textContent = "BM";
  } else {
    langBtn.textContent = "EN";
  }
}
}

function toggleLanguage() {
  if (currentLang === "en") {
    currentLang = "zh-cn";
  } else if (currentLang === "zh-cn") {
    currentLang = "zh-tw";
  } else if (currentLang === "zh-tw") {
    currentLang = "ms";
  } else {
    currentLang = "en";
  }

  localStorage.setItem("heriland-lang", currentLang);

  applyLanguage();

  renderTrailFilters?.();
  renderTrailList?.();
}